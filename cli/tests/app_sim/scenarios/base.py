TYPES = {
    "postgresql": {"pk": "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                   "ts": "timestamp", "json": "jsonb", "float": "double precision"},
    "mysql": {"pk": "bigint AUTO_INCREMENT PRIMARY KEY", "ts": "datetime", "json": "json",
              "float": "double"},
}


def skewed(rng: random.Random, n: int, power: float = 2.0) -> int:
    """1..n with low ids far more likely, like real tenants, customers and devices."""
    return 1 + min(n - 1, int(n * rng.random() ** power))


def unit(key: int, salt: int = 0) -> float:
    """A deterministic value in [0, 1) for an integer key; the seed and traffic both use it."""
    x = (key * 2654435761 + salt * 40503 + 0x9E3779B9) & 0xFFFFFFFF
    x ^= x >> 16
    x = (x * 0x45D9F3B) & 0xFFFFFFFF
    x ^= x >> 16
    return x / 2 ** 32


def expand(template: str, items: list[Any]) -> tuple[str, list[Any]]:
    """Fills `{values}` with one placeholder per item, or one row group per tuple item."""
    if items and isinstance(items[0], tuple):
        group = "(" + ", ".join(["%s"] * len(items[0])) + ")"
        return (template.format(values=", ".join([group] * len(items))),
                [value for row in items for value in row])
    return template.format(values=", ".join(["%s"] * len(items))), list(items)


class Scenario:
    """One simulated application. Subclasses fill in the class attributes and j_/b_ methods."""

    name = ""
    # table -> column specs ("name type ..."); {pk}, {ts}, {json} and {float} are per engine.
    tables: dict[str, tuple[str, ...]] = {}
    # (index, table, columns, unique, plant id or None)
    indexes: tuple[tuple[str, str, tuple[str, ...], bool, str | None], ...] = ()
    base_sizes: dict[str, int] = {}
    # statement name -> SQL, or {"postgresql": sql, "mysql": sql}
    queries: dict[str, str | dict[str, str]] = {}
    journeys: dict[str, int] = {}
    jobs: tuple[tuple[str, float], ...] = ()
    default_rps = 4.0
    default_threads = 3
    # Seed timestamps relative to setup time instead of the fixed ANCHOR.
    live_anchor = False

    def __init__(self, scale: float = 1.0, anchor: datetime | None = None,
                 engine: str = "postgresql") -> None:
        self.scale = scale
        self.anchor = anchor or ANCHOR
        self.engine = engine
        self.n = {table: max(1, int(count * scale)) for table, count in self.base_sizes.items()}
        self.lock = threading.Lock()

    @property
    def database(self) -> str:
        return self.name

    def columns(self, table: str) -> list[str]:
        return [spec.split()[0] for spec in self.tables[table] if not spec.startswith("PRIMARY")]

    def ddl(self, table: str, engine: str) -> str:
        body = ", ".join(self.tables[table]).format(**TYPES[engine])
        return f"CREATE TABLE {table} ({body})"

    @staticmethod
    def index_ddl(name: str, table: str, cols: tuple[str, ...], unique: bool) -> str:
        return f"CREATE {'UNIQUE INDEX' if unique else 'INDEX'} {name} ON {table} ({', '.join(cols)})"

    def sql(self, name: str, engine: str | None = None) -> str:
        query = self.queries[name]
        return query if isinstance(query, str) else query[engine or self.engine]

    def rows(self, table: str, seed: int = 7) -> Iterator[tuple[Any, ...]]:
        raise NotImplementedError

    def pick_journey(self, rng: random.Random) -> str:
        names = list(self.journeys)
        return rng.choices(names, weights=[self.journeys[n] for n in names], k=1)[0]


class Db:
    """One unit of work on a pooled connection. Autocommit unless inside transaction()."""

    def __init__(self, conn: Any, app: Scenario, counts: Counter[str]) -> None:
        self.conn = conn
        self.app = app
        self.counts = counts
        self._in_tx = False

    def _run(self, name: str, sql: str, params: Any, fetch: bool) -> Any:
        with self.conn.cursor() as cursor:
            cursor.execute(sql, params)
            self.counts[name] += 1
            result = cursor.fetchall() if fetch else cursor.rowcount
        if not fetch and not self._in_tx:
            self.conn.commit()
        return result

    def all(self, name: str, **params: Any) -> list[tuple[Any, ...]]:
        return list(self._run(name, self.app.sql(name), params, fetch=True))

    def one(self, name: str, **params: Any) -> tuple[Any, ...] | None:
        rows = self._run(name, self.app.sql(name), params, fetch=True)
        return rows[0] if rows else None

    def execute(self, name: str, **params: Any) -> int:
        return self._run(name, self.app.sql(name), params, fetch=False)

    def insert(self, name: str, **params: Any) -> int:
        sql = self.app.sql(name)
        with self.conn.cursor() as cursor:
            if self.app.engine == "postgresql":
                cursor.execute(sql + " RETURNING id", params)
                new_id = cursor.fetchone()[0]
            else:
                cursor.execute(sql, params)
                new_id = cursor.lastrowid
        self.counts[name] += 1
        if not self._in_tx:
            self.conn.commit()
        return int(new_id)

    def listed(self, name: str, items: list[Any], fetch: bool = True) -> Any:
        """Runs a statement whose `{values}` expands to a list (IN list or multi-row VALUES)."""
        sql, params = expand(self.app.sql(name), items)
        return self._run(name, sql, params, fetch=fetch)

    @contextmanager
    def transaction(self) -> Iterator["Db"]:
        self._in_tx = True
        try:
            yield self
            self.conn.commit()
        except BaseException:
            self.conn.rollback()
            raise
        finally:
            self._in_tx = False

    def finish(self) -> None:
        """Ends any implicit read transaction so the pooled connection holds no snapshot."""
        self.conn.commit()


# Connections


def connect(engine: docker.Engine, database: str | None, user: str | None = None,
            autocommit: bool = False, app_name: str = "appsim") -> Any:
    user = user or docker.APP_USER
    password = (docker.APP_PASSWORD if user == docker.APP_USER else
                docker.MONITOR_PASSWORD if user == docker.MONITOR_USER else docker.ADMIN_PASSWORD)
    if engine is docker.PG:
        import psycopg2

        conn = psycopg2.connect(host="127.0.0.1", port=engine.port, user=user, password=password,
                                dbname=database or "postgres", connect_timeout=5,
                                application_name=app_name)
        conn.autocommit = autocommit
        return conn
    import pymysql

    return pymysql.connect(host="127.0.0.1", port=engine.port, user=user, password=password,
                           database=database, connect_timeout=5, autocommit=autocommit,
                           program_name=app_name)


def admin(engine: docker.Engine, database: str | None = None) -> Any:
    """An autocommit admin connection whose own statements stay out of the statistics."""
    if engine is docker.PG:
        import psycopg2

        conn = psycopg2.connect(host="127.0.0.1", port=engine.port, user=engine.admin_user,
                                password=docker.ADMIN_PASSWORD, dbname=database or "postgres",
                                connect_timeout=5, application_name="appsim-admin",
                                options="-c pg_stat_statements.track=none")
        conn.autocommit = True
        return conn
    conn = connect(engine, None, engine.admin_user, autocommit=True, app_name="appsim-admin")
    with conn.cursor() as cursor:
        cursor.execute("UPDATE performance_schema.threads SET INSTRUMENTED = 'NO' "
                       "WHERE PROCESSLIST_ID = CONNECTION_ID()")
    if database:
        conn.select_db(database)
    return conn


# Lifecycle


def exists(app: Scenario, engine: docker.Engine) -> bool:
    conn = admin(engine)
    with conn.cursor() as cursor:
        if engine is docker.PG:
            cursor.execute("SELECT 1 FROM pg_database WHERE datname = %s", (app.database,))
        else:
            cursor.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name = %s",
                           (app.database,))
        found = cursor.fetchone() is not None
    conn.close()
    return found


def drop(app: Scenario, engine: docker.Engine) -> None:
    if app.database in ("", docker.DATABASE, "postgres", "mysql", "sys"):
        raise ValueError(f"refusing to drop {app.database!r}")
    conn = admin(engine)
    with conn.cursor() as cursor:
        if engine is docker.PG:
            cursor.execute(f"DROP DATABASE IF EXISTS {app.database} WITH (FORCE)")
        else:
            cursor.execute(f"DROP DATABASE IF EXISTS {app.database}")
    conn.close()


def _copy_value(value: Any) -> str:
    if value is None:
        return "\\N"
    return str(value).replace("\\", "\\\\").replace("\t", " ").replace("\n", " ")


def load(app: Scenario, conn: Any, engine: str, seed: int, log: Callable[[str], None]) -> int:
    """Creates and fills the tables, then builds the indexes and analyzes. Returns rows written."""
    total = 0
    with conn.cursor() as cursor:
        for table in app.tables:
            cursor.execute(app.ddl(table, engine))
            cols = app.columns(table)
            batch: list[tuple[Any, ...]] = []
            written = 0

            def flush() -> None:
                if not batch:
                    return
                if engine == "postgresql":
                    buf = io.StringIO("".join("\t".join(_copy_value(v) for v in row) + "\n"
                                              for row in batch))
                    cursor.copy_expert(f"COPY {table} ({', '.join(cols)}) FROM STDIN", buf)
                else:
                    marks = ", ".join(["%s"] * len(cols))
                    cursor.executemany(
                        f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({marks})", batch)
                batch.clear()

            for row in app.rows(table, seed):
                batch.append(row)
                written += 1
                if len(batch) >= BATCH:
                    flush()
            flush()
            if engine == "postgresql" and "id {pk}" in app.tables[table] and written:
                cursor.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                               f"(SELECT max(id) FROM {table}))")
            total += written
            log(f"  {engine} {app.database}: {table} {written} rows")
        for name, table, cols, unique, _plant in app.indexes:
            cursor.execute(app.index_ddl(name, table, cols, unique))
        for table in app.tables:
            if engine == "mysql":
                cursor.execute(f"ANALYZE TABLE {table}")
                cursor.fetchall()
            else:
                cursor.execute(f"VACUUM ANALYZE {table}")
    return total


def setup(app: Scenario, engine: docker.Engine, seed: int = 7,
          log: Callable[[str], None] = print) -> dict[str, Any]:
    """(Re)creates the scenario database, seeds it and grants the monitor user read access."""
    free = docker.free_gb()
    if free < docker.MIN_FREE_GB:
        raise SystemExit(f"Only {free:.1f} GB free on /mnt/c; refusing (need "
                         f"{docker.MIN_FREE_GB}).")
    started = time.monotonic()
    db, mon, owner = app.database, docker.MONITOR_USER, docker.APP_USER
    drop(app, engine)
    conn = admin(engine)
    with conn.cursor() as cursor:
        if engine is docker.PG:
            cursor.execute(f"CREATE DATABASE {db} OWNER {owner}")
            cursor.execute(f"GRANT CONNECT ON DATABASE {db} TO {mon}")
        else:
            cursor.execute(f"CREATE DATABASE {db}")
            cursor.execute(f"GRANT ALL PRIVILEGES ON {db}.* TO '{owner}'@'%'")
            cursor.execute(f"GRANT SELECT ON {db}.* TO '{mon}'@'%'")
    conn.close()
    if engine is docker.PG:
        conn = admin(engine, db)
        with conn.cursor() as cursor:
            cursor.execute("CREATE EXTENSION IF NOT EXISTS pg_stat_statements")
        conn.close()
        conn = connect(engine, db, owner, autocommit=True, app_name="appsim-setup")
        total = load(app, conn, engine.name, seed, log)
        with conn.cursor() as cursor:
            for statement in (
                    f"GRANT USAGE ON SCHEMA public TO {mon}",
                    f"GRANT SELECT ON ALL TABLES IN SCHEMA public TO {mon}",
                    f"ALTER DEFAULT PRIVILEGES FOR ROLE {owner} IN SCHEMA public "
                    f"GRANT SELECT ON TABLES TO {mon}"):
                cursor.execute(statement)
        conn.close()
        # The seed ran as the owner; clear this database's statement and table counters only.
        conn = admin(engine, db)
        with conn.cursor() as cursor:
            cursor.execute("SELECT pg_stat_statements_reset(0, (SELECT oid FROM pg_database "
                           "WHERE datname = %s), 0)", (db,))
            cursor.execute("SELECT pg_stat_reset()")
        conn.close()
    else:
        conn = admin(engine, db)
        total = load(app, conn, engine.name, seed, log)
        conn.close()
    size = size_mb(app, engine)
    if size > MAX_DB_MB:
        log(f"  WARNING: {engine.name} {db} is {size:.0f} MB, over the {MAX_DB_MB:.0f} MB budget")
    return {"engine": engine.name, "database": db, "rows": total, "size_mb": round(size, 1),
            "seconds": round(time.monotonic() - started, 1)}


def size_mb(app: Scenario, engine: docker.Engine) -> float:
    conn = admin(engine)
    with conn.cursor() as cursor:
        if engine is docker.PG:
            cursor.execute("SELECT pg_database_size(%s)", (app.database,))
        else:
            cursor.execute("SELECT COALESCE(SUM(data_length + index_length), 0) FROM "
                           "information_schema.tables WHERE table_schema = %s", (app.database,))
        size = float(cursor.fetchone()[0] or 0)
    conn.close()
    return size / 1e6


def status(app: Scenario, engine: docker.Engine, top: int = 15) -> dict[str, Any]:
    """Size, row counts, write counters, index use and the top statements of this database."""
    out: dict[str, Any] = {"engine": engine.name, "database": app.database}
    if not exists(app, engine):
        out["state"] = "absent"
        return out
    out["size_mb"] = round(size_mb(app, engine), 1)
    conn = admin(engine, app.database)
    with conn.cursor() as cursor:
        if engine is docker.PG:
            cursor.execute("SELECT relname, n_live_tup, seq_scan, idx_scan, n_tup_ins, "
                           "n_tup_upd, n_tup_del FROM pg_stat_user_tables ORDER BY relname")
            out["tables"] = [list(r) for r in cursor.fetchall()]
            cursor.execute("SELECT indexrelname, idx_scan FROM pg_stat_user_indexes "
                           "ORDER BY relname, indexrelname")
            out["index_scans"] = dict(cursor.fetchall())
            cursor.execute(
                "SELECT calls, round(total_exec_time::numeric, 1), rows, "
                "left(regexp_replace(query, '\\s+', ' ', 'g'), 140) FROM pg_stat_statements "
                "WHERE dbid = (SELECT oid FROM pg_database WHERE datname = %s) "
                "ORDER BY calls DESC LIMIT %s", (app.database, top))
        else:
            cursor.execute("SELECT OBJECT_NAME, COUNT_FETCH, COUNT_INSERT, COUNT_UPDATE, "
                           "COUNT_DELETE FROM performance_schema.table_io_waits_summary_by_table "
                           "WHERE OBJECT_SCHEMA = %s ORDER BY OBJECT_NAME", (app.database,))
            out["tables"] = [list(r) for r in cursor.fetchall()]
            cursor.execute("SELECT INDEX_NAME, COUNT_FETCH FROM "
                           "performance_schema.table_io_waits_summary_by_index_usage "
                           "WHERE OBJECT_SCHEMA = %s AND INDEX_NAME IS NOT NULL "
                           "ORDER BY OBJECT_NAME, INDEX_NAME", (app.database,))
            out["index_scans"] = {name: int(count) for name, count in cursor.fetchall()}
            cursor.execute(
                "SELECT COUNT_STAR, ROUND(SUM_TIMER_WAIT / 1e9, 1), SUM_ROWS_EXAMINED, "
                "LEFT(DIGEST_TEXT, 140) FROM performance_schema.events_statements_summary_by_digest "
                "WHERE SCHEMA_NAME = %s ORDER BY COUNT_STAR DESC LIMIT %s", (app.database, top))
        out["top_statements"] = [[int(r[0]), float(r[1] or 0), int(r[2] or 0), r[3]]
                                 for r in cursor.fetchall()]
    conn.close()
    return out


# Traffic


class Driver:
    """Worker threads draw journeys from a Poisson process; a jobs thread runs fixed intervals.

    Every thread has its own RNG derived from the run seed, so a run's choices repeat exactly.
    """

    def __init__(self, app: Scenario, engine: docker.Engine, *, rps: float, threads: int,
                 seed: int = 20261007, jobs: bool = True) -> None:
        self.app = app
        self.engine = engine
        app.engine = engine.name
        self.pool = Pool(lambda: connect(engine, app.database, app_name=f"appsim-{app.name}"),
                         threads + 1)
        self.rps = rps
        self.threads = threads
        self.seed = seed
        self.jobs_enabled = jobs and bool(app.jobs)
        self.statements: Counter[str] = Counter()
        self.journeys: Counter[str] = Counter()
        self.errors: Counter[str] = Counter()
        self.last_error: dict[str, str] = {}
        self._stop = threading.Event()
        self._lock = threading.Lock()
        self._threads: list[threading.Thread] = []
        self.started_at = 0.0

    def rng(self, role: str) -> random.Random:
        return random.Random(f"{self.seed}:{self.app.name}:{self.engine.name}:{role}")

    def start(self) -> None:
        self.started_at = time.time()
        for index in range(self.threads):
            self._threads.append(threading.Thread(
                target=self._worker, args=(self.rng(f"worker:{index}"),), daemon=True,
                name=f"{self.app.name}-{self.engine.name}-{index}"))
        if self.jobs_enabled:
            self._threads.append(threading.Thread(
                target=self._jobs, args=(self.rng("jobs"),), daemon=True,
                name=f"{self.app.name}-{self.engine.name}-jobs"))
        for thread in self._threads:
            thread.start()

    def stop(self) -> None:
        self._stop.set()
        for thread in self._threads:
            thread.join(timeout=60)
        self.pool.close()

    def summary(self) -> dict[str, Any]:
        elapsed = max(1.0, time.time() - self.started_at)
        with self._lock:
            total = sum(self.statements.values())
            return {"scenario": self.app.name, "engine": self.engine.name,
                    "elapsed_s": round(elapsed, 1), "statements": total,
                    "per_s": round(total / elapsed, 1), "journeys": dict(self.journeys),
                    "errors": dict(self.errors), "last_error": dict(self.last_error)}

    def _worker(self, rng: random.Random) -> None:
        mean_gap = self.threads / self.rps
        next_at = time.monotonic() + rng.random() * mean_gap
        while not self._stop.is_set():
            wait = next_at - time.monotonic()
            if wait > 0:
                self._stop.wait(wait)
                continue
            # A worker that fell far behind resumes the schedule instead of bursting to catch up.
            next_at = max(next_at, time.monotonic() - 2.0) + rng.expovariate(1.0 / mean_gap)
            journey = self.app.pick_journey(rng)
            self._guard(journey, getattr(self.app, f"j_{journey}"), rng)

    def _jobs(self, rng: random.Random) -> None:
        now = time.monotonic()
        intervals = dict(self.app.jobs)
        due = {name: now + every * (0.3 + 0.7 * rng.random()) for name, every in intervals.items()}
        while not self._stop.is_set():
            name = min(due, key=due.get)
            wait = due[name] - time.monotonic()
            if wait > 0:
                self._stop.wait(min(wait, 1.0))
                continue
            due[name] = time.monotonic() + intervals[name]
            self._guard(f"job:{name}", getattr(self.app, f"b_{name}"), rng)

    def _guard(self, name: str, body: Callable[[Db, random.Random], None],
               rng: random.Random) -> None:
        local: Counter[str] = Counter()
        try:
            with self.pool.connection() as conn:
                db = Db(conn, self.app, local)
                try:
                    body(db, rng)
                finally:
                    db.finish()
            ok = True
        except Exception as exc:
            ok = False
            with self._lock:
                self.errors[name] += 1
                self.last_error[name] = str(exc)[:300]
            logger.debug("%s %s %s failed: %s", self.app.name, self.engine.name, name, exc)
            # Back off briefly so a dead server doesn't turn into a reconnect storm.
            self._stop.wait(0.5)
        with self._lock:
            self.statements.update(local)
            if ok:
                self.journeys[name] += 1


def run(drivers: list[Driver], duration: float, report_every: float = 60.0,
        log: Callable[[str], None] = print) -> list[dict[str, Any]]:
    stop = threading.Event()

    def on_signal(_signum: int, _frame: Any) -> None:
        stop.set()

    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGINT, on_signal)
    for driver in drivers:
        driver.start()
    deadline = time.monotonic() + duration
    next_report = time.monotonic() + report_every
    try:
        while not stop.is_set() and time.monotonic() < deadline:
            stop.wait(min(1.0, max(0.0, deadline - time.monotonic())))
            if time.monotonic() >= next_report:
                next_report += report_every
                free = docker.free_gb()
                if free < docker.MIN_FREE_GB:
                    log(f"Only {free:.1f} GB free on /mnt/c (need {docker.MIN_FREE_GB}); "
                        "stopping traffic.")
                    break
                for driver in drivers:
                    s = driver.summary()
                    log(f"{datetime.now():%H:%M:%S} [{s['scenario']} {s['engine']}] "
                        f"{s['elapsed_s']:.0f}s {s['statements']} stmts ({s['per_s']}/s) "
                        f"errors={sum(s['errors'].values())}")
    finally:
        if stop.is_set():
            log("Stopping.")
        for driver in drivers:
            driver.stop()
    return [driver.summary() for driver in drivers]
