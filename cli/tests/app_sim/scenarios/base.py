"""Shared machinery for app-sim scenarios: database lifecycle, seeding and a traffic driver.

A scenario is a Scenario subclass with its own database (same name on both engines), tables,
indexes, named statements, deterministic seed rows, weighted journeys and background jobs. It
lives in the existing app-sim containers: shop_app owns the tables on PostgreSQL and the
read-only rdst_monitor user gets the same grants it has on shop.

Admin connections made here switch off their own statement tracking, so setup and status never
show up in the scenario's pg_stat_statements or performance_schema digests.
"""

